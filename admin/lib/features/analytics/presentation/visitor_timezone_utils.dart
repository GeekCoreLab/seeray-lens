/// Resolved timezone information including offset and daylight saving time status.
class TimezoneResolution {
  const TimezoneResolution({
    required this.name,
    required this.offsetMinutes,
    required this.isDst,
  });

  final String name;
  final int offsetMinutes;
  final bool isDst;

  Duration get offset => Duration(minutes: offsetMinutes);

  DateTime toZoned(DateTime utcTime) {
    final utc = utcTime.isUtc ? utcTime : utcTime.toUtc();
    return utc.add(offset);
  }

  String formatOffset() {
    final sign = offsetMinutes >= 0 ? '+' : '-';
    final absMinutes = offsetMinutes.abs();
    final hours = absMinutes ~/ 60;
    final minutes = absMinutes % 60;
    if (minutes == 0) {
      return 'UTC$sign$hours';
    }
    return 'UTC$sign$hours:${minutes.toString().padLeft(2, '0')}';
  }
}

