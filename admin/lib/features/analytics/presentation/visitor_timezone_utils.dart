TimezoneResolution resolveTimezone(String? timezoneName, {String? countryCode}) {
  var target = timezoneName?.trim();
  if ((target == null || target.isEmpty) && countryCode != null && countryCode.trim().isNotEmpty) {
    target = countryDefaultTimezone[countryCode.trim().toUpperCase()];
  }
  if (target == null || target.isEmpty) {
    return const TimezoneResolution(
      name: 'UTC',
      offsetMinutes: 0,
      isDst: false,
    );
  }
  final known = knownTimezones[target];
  if (known != null) {
    return TimezoneResolution(
      name: target,
      offsetMinutes: known.offsetMinutes,
      isDst: known.isDst,
    );
  }

  // Fallback for custom UTC offsets like "UTC+8", "GMT-4", "+08:00"
  final upper = target.toUpperCase();
  final match = RegExp(r'^(?:UTC|GMT)?([+-])(\d{1,2})(?::?(\d{2}))?$').firstMatch(upper);
  if (match != null) {
    final sign = match.group(1) == '-' ? -1 : 1;
    final hours = int.parse(match.group(2)!);
    final minutes = match.group(3) != null ? int.parse(match.group(3)!) : 0;
    final total = sign * (hours * 60 + minutes);
    return TimezoneResolution(
      name: target,
      offsetMinutes: total,
      isDst: false,
    );
  }

  return TimezoneResolution(
    name: target,
    offsetMinutes: 0,
    isDst: false,
  );
}

/// Formats the dual-timezone comparison display:
/// “以我的时区显示的时间 - 时区 - 以访客时区显示的时间” (如果有夏令时则标记在时区中)
///
/// Example:
/// "今天 10:04 (UTC+8) - America/Los_Angeles · 夏令时 - 昨天 19:04 (UTC-7)"
String formatTimezoneComparison({
  required BuildContext context,
  required DateTime time,
  required String? visitorTimezone,
  String? countryCode,
  DateTime? now,
}) {
  final utcTime = time.isUtc ? time : time.toUtc();
  final myLocal = utcTime.toLocal();
  final myFormattedTime = formatTimelineTime(context, myLocal, now: now);
  final myOffset = myLocal.timeZoneOffset;
  final myOffsetMinutes = myOffset.inMinutes;
  final mySign = myOffsetMinutes >= 0 ? '+' : '-';
  final myHours = myOffsetMinutes.abs() ~/ 60;
  final myMins = myOffsetMinutes.abs() % 60;
  final myOffsetStr = myMins == 0 ? 'UTC$mySign$myHours' : 'UTC$mySign$myHours:${myMins.toString().padLeft(2, '0')}';

  final visitorTz = resolveTimezone(visitorTimezone, countryCode: countryCode);
  final visitorLocal = visitorTz.toZoned(utcTime);
  final visitorFormattedTime = formatTimelineTime(context, visitorLocal, now: now);

  final isChinese = Localizations.localeOf(context).languageCode == 'zh';
  final dstBadge = visitorTz.isDst
      ? (isChinese ? ' · 夏令时' : ' · DST')
      : '';

  final visitorTzDisplay = '${visitorTz.name}$dstBadge';

  return '$myFormattedTime ($myOffsetStr) - $visitorTzDisplay - $visitorFormattedTime (${visitorTz.formatOffset()})';
}

/// Widget displaying a visitor timezone chip with detailed comparison dialog or tooltip.
class VisitorTimezoneBadge extends StatelessWidget {
  const VisitorTimezoneBadge({
    required this.time,
    this.visitorTimezone,
    this.countryCode,
    super.key,
  });

  final DateTime time;
  final String? visitorTimezone;
  final String? countryCode;

  @override
  Widget build(BuildContext context) {
    final comparison = formatTimezoneComparison(
      context: context,
      time: time,
      visitorTimezone: visitorTimezone,
      countryCode: countryCode,
    );
    final tz = resolveTimezone(visitorTimezone, countryCode: countryCode);
    final isChinese = Localizations.localeOf(context).languageCode == 'zh';
    final dstText = tz.isDst ? (isChinese ? ' [夏令时]' : ' [DST]') : '';
    final label = '${tz.name}$dstText · ${tz.formatOffset()}';

    return Tooltip(
      message: comparison,
      child: Chip(
        avatar: const Icon(Icons.schedule_outlined, size: 16),
        label: Text(label, maxLines: 1, overflow: TextOverflow.ellipsis),
        visualDensity: VisualDensity.compact,
        padding: EdgeInsets.zero,
      ),
    );
  }
}

