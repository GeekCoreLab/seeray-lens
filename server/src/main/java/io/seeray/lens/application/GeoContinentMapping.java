    private GeoContinentMapping() {}

    public static String resolve(String rawContinent, String countryCode) {
        if (rawContinent != null && !rawContinent.isBlank()) {
            String normalized = rawContinent.trim().toUpperCase(Locale.ROOT);
            if (VALID_CODES.contains(normalized)) return normalized;
            String byName = CONTINENT_NAMES.get(normalized);
            if (byName != null) return byName;
        }
        if (countryCode == null || countryCode.isBlank()) return null;
        return COUNTRY_TO_CONTINENT.get(countryCode.trim().toUpperCase(Locale.ROOT));
    }
